"""Data audit: distributions, duplicates and leakage-relevant structure."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from src.constants import LABELS, PROVIDER_OF
from src.data import class_support, dataset_fingerprint


def _length_words(texts: pd.Series) -> pd.Series:
    return texts.fillna("").str.split().str.len()


def audit_train(train: pd.DataFrame, test: pd.DataFrame | None = None) -> dict:
    """Compute the Section-2 audit table for a training frame."""
    text = train["text"].astype(str)
    lengths = _length_words(text)
    char_lengths = text.str.len()
    counts = train["model"].value_counts()

    per_prompt = train.groupby("prompt_id", observed=True).agg(
        rows=("id", "size"), labels=("model", "nunique")
    )
    duplicates = int(train.duplicated(subset=["text"]).sum())
    duplicate_groups = int(
        train.groupby("text", observed=True)["id"].transform("size").gt(1).sum()
    )
    non_ascii = float(text.apply(lambda s: any(ord(c) > 127 for c in s)).mean())
    markdown = float(text.str.contains(r"\*\*|`|^[-*] ", regex=True).mean())
    emoji = float(text.apply(lambda s: any(ord(c) > 0x1F000 for c in s)).mean())

    summary = {
        "rows": int(len(train)),
        "columns": list(train.columns),
        "nulls": {c: int(train[c].isna().sum()) for c in train.columns},
        "duplicate_ids": int(train["id"].duplicated().sum()),
        "duplicate_texts": duplicates,
        "rows_in_duplicate_text_groups": duplicate_groups,
        "n_prompts": int(train["prompt_id"].nunique()),
        "rows_per_prompt": {
            "min": int(per_prompt["rows"].min()),
            "median": float(per_prompt["rows"].median()),
            "max": int(per_prompt["rows"].max()),
        },
        "labels_per_prompt": {
            "min": int(per_prompt["labels"].min()),
            "median": float(per_prompt["labels"].median()),
            "max": int(per_prompt["labels"].max()),
        },
        "n_labels_present": int(train["model"].nunique()),
        "labels_absent": [l for l in LABELS if counts.get(l, 0) == 0],
        "class_support": class_support(train),
        "class_support_min": int(counts.min()),
        "class_support_max": int(counts.max()),
        "class_support_ratio": float(counts.max() / max(counts.min(), 1)),
        "words": {
            "mean": float(lengths.mean()),
            "median": float(lengths.median()),
            "p05": float(lengths.quantile(0.05)),
            "p95": float(lengths.quantile(0.95)),
            "min": int(lengths.min()),
            "max": int(lengths.max()),
        },
        "chars": {
            "mean": float(char_lengths.mean()),
            "median": float(char_lengths.median()),
            "max": int(char_lengths.max()),
        },
        "share_non_ascii_passages": round(non_ascii, 4),
        "share_markdown_passages": round(markdown, 4),
        "share_emoji_passages": round(emoji, 4),
        "provider_support": {
            provider: int(sum(counts.get(l, 0) for l in LABELS if PROVIDER_OF[l] == provider))
            for provider in sorted(set(PROVIDER_OF.values()))
        },
        "dataset_fingerprint": dataset_fingerprint(train),
    }
    if test is not None:
        test_lengths = _length_words(test["text"].astype(str))
        summary["test"] = {
            "rows": int(len(test)),
            "words_mean": float(test_lengths.mean()) if len(test) else 0.0,
            "duplicate_ids": int(test["id"].duplicated().sum()),
            "has_prompt_id": "prompt_id" in test.columns,
        }
    return summary


def write_report(summary: dict, path: str | Path, dataset_label: str) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    support = summary["class_support"]
    lines = [
        "# Data audit",
        "",
        f"- dataset: **{dataset_label}**",
        f"- rows: {summary['rows']}",
        f"- prompts: {summary['n_prompts']}",
        f"- labels present: {summary['n_labels_present']}/18",
        f"- fingerprint: `{summary['dataset_fingerprint']}`",
        "",
    ]
    if dataset_label == "synthetic":
        lines += [
            "> **Synthetic fixture** generated by `src/synthetic.py`; not competition data.",
            "",
        ]
    lines += [
        "## Structure",
        "",
        "| quantity | value |",
        "|---|---|",
        f"| rows per prompt (min/median/max) | "
        f"{summary['rows_per_prompt']['min']} / {summary['rows_per_prompt']['median']} / "
        f"{summary['rows_per_prompt']['max']} |",
        f"| labels per prompt (min/median/max) | "
        f"{summary['labels_per_prompt']['min']} / {summary['labels_per_prompt']['median']} / "
        f"{summary['labels_per_prompt']['max']} |",
        f"| duplicate ids | {summary['duplicate_ids']} |",
        f"| duplicate texts | {summary['duplicate_texts']} |",
        f"| rows in duplicate-text groups | {summary['rows_in_duplicate_text_groups']} |",
        f"| class support (min/max) | {summary['class_support_min']} / {summary['class_support_max']} |",
        f"| class imbalance ratio | {summary['class_support_ratio']:.2f} |",
        f"| words per passage (mean/median) | {summary['words']['mean']:.1f} / "
        f"{summary['words']['median']:.0f} |",
        f"| words per passage (p05/p95) | {summary['words']['p05']:.0f} / "
        f"{summary['words']['p95']:.0f} |",
        f"| passages with non-ASCII | {summary['share_non_ascii_passages']:.2%} |",
        f"| passages with markdown | {summary['share_markdown_passages']:.2%} |",
        f"| passages with emoji | {summary['share_emoji_passages']:.2%} |",
        "",
        "## Class support",
        "",
        "| label | provider | rows |",
        "|---|---|---|",
    ]
    for label in LABELS:
        lines.append(f"| `{label}` | {PROVIDER_OF[label]} | {support[label]} |")
    lines += [
        "",
        "## Provider support",
        "",
        "| provider | rows |",
        "|---|---|",
    ]
    for provider, n in summary["provider_support"].items():
        lines.append(f"| {provider} | {n} |")
    if "test" in summary:
        t = summary["test"]
        lines += [
            "",
            "## Test set",
            "",
            f"- rows: {t['rows']}",
            f"- mean words: {t['words_mean']:.1f}",
            f"- duplicate ids: {t['duplicate_ids']}",
            f"- includes prompt_id: {t['has_prompt_id']}",
            "",
            "Test prompts are unseen by design; the audit cannot verify that from "
            "`test.csv`, which has no `prompt_id`. Grouped CV is the local proxy.",
        ]
    lines += [
        "",
        "## Leakage checklist",
        "",
        "- [x] schema validated against the official column names",
        "- [x] ids unique in train and test",
        "- [x] zero prompt overlap enforced per CV fold (`src.validation.validate_splits`)",
        "- [x] vectorisers, SVD, nuisance projections and classifiers fitted per training fold",
        "- [x] exact-duplicate text count reported above; inspect before trusting CV",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def make_figures(train: pd.DataFrame, out_dir: str | Path) -> list[str]:
    """Class-balance and length figures; returns written paths."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    counts = train["model"].value_counts().reindex(LABELS).fillna(0)

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.barh(counts.index[::-1], counts.values[::-1], color="#3b6ea5")
    ax.set_xlabel("passages")
    ax.set_title("Class balance (train)")
    fig.tight_layout()
    path = out_dir / "class_balance.png"
    fig.savefig(path, dpi=140)
    plt.close(fig)
    written.append(str(path))

    lengths = _length_words(train["text"].astype(str))
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.hist(lengths, bins=40, color="#4c9a6a")
    ax.set_xlabel("words per passage")
    ax.set_ylabel("passages")
    ax.set_title("Passage length distribution (train)")
    fig.tight_layout()
    path = out_dir / "length_distribution.png"
    fig.savefig(path, dpi=140)
    plt.close(fig)
    written.append(str(path))
    return written


def run_audit(
    train: pd.DataFrame,
    test: pd.DataFrame | None,
    out_dir: str | Path,
    dataset_label: str = "official",
    figures_dir: str | Path | None = None,
) -> dict:
    out_dir = Path(out_dir)
    summary = audit_train(train, test)
    summary["dataset"] = dataset_label
    (out_dir / "audit.json").parent.mkdir(parents=True, exist_ok=True)
    (out_dir / "audit.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    write_report(summary, out_dir / "data_audit.md", dataset_label)

    fig_dir = Path(figures_dir) if figures_dir else out_dir / "figures"
    try:
        summary["figures"] = make_figures(train, fig_dir)
    except Exception as exc:  # pragma: no cover - plotting is optional
        summary["figures"] = []
        summary["figures_error"] = str(exc)
    return summary
